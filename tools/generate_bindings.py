#!/usr/bin/env python3
"""Generate language bindings from the public ABI, or check checked-in copies."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENTRIES = [
    ("init", "ubyte baud @A, uword port @XY", "ubyte @A, bool @Pc"),
    ("shutdown", "", "ubyte @A, bool @Pc"),
    ("get_byte", "", "ubyte @A, bool @Pc"),
    ("put_byte", "ubyte value @A", "ubyte @A, bool @Pc"),
    ("read", "ubyte length @A, uword buffer @XY", "ubyte @A, uword @XY, bool @Pc"),
    ("write", "ubyte length @A, uword buffer @XY", "ubyte @A, uword @XY, bool @Pc"),
    ("status", "", "ubyte @A, ubyte @X, ubyte @Y, bool @Pc"),
    ("set_timeout", "ubyte high @A, uword low @XY", "ubyte @A, bool @Pc"),
    ("prepare", "", "ubyte @A, bool @Pc"),
    ("connect", "uword endpoint @XY", "ubyte @A, bool @Pc"),
    ("disconnect", "", "ubyte @A, bool @Pc"),
    ("abi_info", "", "ubyte @A, uword @XY, bool @Pc"),
]
ERRORS = ["OK", "AGAIN", "TIMEOUT", "BADARG", "NOCARD", "STATE", "EOF", "IOERR", "MODEM", "OVERFLOW"]

def outputs():
    p8 = "; Generated by tools/generate_bindings.py. Default binary address $8000.\nx16net {\n"
    inc = "; Generated by tools/generate_bindings.py. Default binary address $8000.\n"
    for i, name in enumerate(ERRORS):
        p8 += f"    const ubyte ERR_{name} = {i}\n"
        inc += f"X16NET_ERR_{name} = {i}\n"
    for i, (name, args, returns) in enumerate(ENTRIES):
        address = 0x8000 + i * 3
        clobbers = "" if "@XY" in returns or "@X," in returns else "X,Y"
        p8 += f"    extsub ${address:04x} = {name}({args}) clobbers({clobbers}) -> {returns}\n"
        inc += f"X16NET_{name.upper()} = ${address:04x}\n"
    p8 += "}\n"
    return {ROOT / "prog8/x16net.p8": p8, ROOT / "include/x16net.inc": inc}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale binding: {path.relative_to(ROOT)}; run tools/generate_bindings.py")
        else:
            path.write_text(content)

if __name__ == "__main__":
    main()
